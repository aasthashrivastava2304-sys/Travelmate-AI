import React, { useState, useEffect } from 'react';
import { Sidebar, NavigationTab } from './components/Sidebar';
import { TopBar } from './components/TopBar';
import { DashboardView } from './components/DashboardView';
import { TripPlannerView } from './components/TripPlannerView';
import { ItineraryDetailView } from './components/ItineraryDetailView';
import { MyTripsView } from './components/MyTripsView';
import { ExploreView } from './components/ExploreView';
import { SettingsView } from './components/SettingsView';
import { Trip } from './types/travel';
import {
  getStoredTrips,
  saveTrip,
  deleteTrip,
  duplicateTrip,
  resetToSampleData,
  clearAllTrips,
  getUserSettings,
  UserSettings,
} from './utils/storage';

export default function App() {
  const [currentTab, setCurrentTab] = useState<NavigationTab>('dashboard');
  const [mobileSidebarOpen, setMobileSidebarOpen] = useState(false);
  const [trips, setTrips] = useState<Trip[]>([]);
  const [activeTripId, setActiveTripId] = useState<string | null>(null);
  const [plannerPrefill, setPlannerPrefill] = useState<string>('');
  const [userSettings, setUserSettings] = useState<UserSettings>(getUserSettings());
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  // Load trips on initial render
  useEffect(() => {
    const loaded = getStoredTrips();
    setTrips(loaded);
  }, []);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(null), 3000);
  };

  // Switch to Trip Planner
  const handlePlanTrip = (destination?: string) => {
    setPlannerPrefill(destination || '');
    setActiveTripId(null);
    setCurrentTab('planner');
  };

  // Switch to specific Trip Itinerary Detail view
  const handleSelectTrip = (tripId: string) => {
    setActiveTripId(tripId);
    setCurrentTab('my-trips');
  };

  // When a new trip is generated by planner
  const handleTripGenerated = (newTrip: Trip) => {
    saveTrip(newTrip);
    setTrips(getStoredTrips());
    setActiveTripId(newTrip.id);
    showToast(`Itinerary for ${newTrip.destination} successfully created!`);
  };

  // Update existing trip
  const handleUpdateTrip = (updatedTrip: Trip) => {
    saveTrip(updatedTrip);
    setTrips(getStoredTrips());
    showToast('Trip itinerary updated.');
  };

  // Duplicate trip
  const handleDuplicate = (tripId: string) => {
    const dup = duplicateTrip(tripId);
    if (dup) {
      setTrips(getStoredTrips());
      showToast(`Duplicated "${dup.title}".`);
    }
  };

  // Delete trip
  const handleDelete = (tripId: string) => {
    const remaining = deleteTrip(tripId);
    setTrips(remaining);
    if (activeTripId === tripId) {
      setActiveTripId(null);
    }
    showToast('Trip deleted from workspace.');
  };

  // Reset to initial sample data
  const handleResetSample = () => {
    const resetted = resetToSampleData();
    setTrips(resetted);
    setActiveTripId(null);
    showToast('Reset to original sample itineraries.');
  };

  // Clear all trips
  const handleClearAll = () => {
    clearAllTrips();
    setTrips([]);
    setActiveTripId(null);
    showToast('All trips cleared.');
  };

  const activeTrip = trips.find((t) => t.id === activeTripId);

  return (
    <div className="min-h-screen bg-[#f8f9fa] text-slate-900 flex">
      {/* Toast feedback */}
      {toastMessage && (
        <div className="fixed bottom-6 right-6 z-50 px-4 py-2.5 bg-slate-900 text-white text-xs font-semibold rounded-xl shadow-lg border border-slate-700 animate-fade-in flex items-center gap-2">
          <span>{toastMessage}</span>
        </div>
      )}

      {/* Sidebar Navigation */}
      <Sidebar
        currentTab={activeTripId ? 'my-trips' : currentTab}
        onSelectTab={(tab) => {
          setActiveTripId(null);
          setCurrentTab(tab);
        }}
        userSettings={userSettings}
        tripsCount={trips.length}
        mobileOpen={mobileSidebarOpen}
        onCloseMobile={() => setMobileSidebarOpen(false)}
      />

      {/* Main Content Area */}
      <div className="flex-1 flex flex-col min-w-0 lg:pl-72">
        {/* Top Header */}
        <TopBar
          currentTab={currentTab}
          onOpenMobile={() => setMobileSidebarOpen(true)}
          onPlanNewTrip={() => handlePlanTrip()}
        />

        {/* View Routing */}
        <main className="flex-1 p-4 sm:p-8 overflow-y-auto">
          {activeTrip ? (
            <ItineraryDetailView
              trip={activeTrip}
              onUpdateTrip={handleUpdateTrip}
              onBackToTrips={() => setActiveTripId(null)}
            />
          ) : currentTab === 'dashboard' ? (
            <DashboardView
              trips={trips}
              userSettings={userSettings}
              onPlanTrip={handlePlanTrip}
              onSelectTrip={handleSelectTrip}
              onExploreDestinations={() => setCurrentTab('explore')}
            />
          ) : currentTab === 'planner' ? (
            <TripPlannerView
              initialDestination={plannerPrefill}
              onTripGenerated={handleTripGenerated}
            />
          ) : currentTab === 'my-trips' ? (
            <MyTripsView
              trips={trips}
              onSelectTrip={handleSelectTrip}
              onPlanTrip={() => handlePlanTrip()}
              onDuplicateTrip={handleDuplicate}
              onDeleteTrip={handleDelete}
              onUpdateTrip={handleUpdateTrip}
            />
          ) : currentTab === 'explore' ? (
            <ExploreView onPlanDestination={(dest) => handlePlanTrip(dest)} />
          ) : currentTab === 'settings' ? (
            <SettingsView
              userSettings={userSettings}
              onUpdateSettings={setUserSettings}
              trips={trips}
              onResetSampleData={handleResetSample}
              onClearAllTrips={handleClearAll}
            />
          ) : null}
        </main>
      </div>
    </div>
  );
}
